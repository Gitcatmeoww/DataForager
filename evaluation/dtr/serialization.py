"""Turn corpus rows into the two kinds of input the DTR towers expect.

The two towers are fed very differently, following
tapas/retrieval/tf_example_utils.py in google-research/tapas:

- Table tower: the table title goes in the text slot, followed by the flattened
  table, so the input is [CLS] title [SEP] flattened table. TAPAS then adds its
  seven token type ids (segment, column, row, previous labels, column ranks,
  inverse column ranks, numeric relations). Rows are dropped until the sequence
  fits, matching the trimming loop in the original.
- Query tower: plain text only, [CLS] question [SEP], with an empty table. The
  original zeroes all seven token type ids and caps the query at its own,
  shorter max_query_length. See the "Arrange features for query, such that it is
  assigned with an empty table" block of table_retriever_model.py.

Corpus tables reach us as markdown, which parse_markdown_table converts back to
a DataFrame. The same parser handles hypothetical schemas generated by HySE, so
that HySE-over-DTR encodes its schemas exactly the way the corpus was encoded.
"""

import pandas as pd
import torch

# Header plus two example rows is short, so the table tower does not need the
# 512 positions the paper used. Halving it is what makes a 256-example batch fit
# in memory. Recorded as a deviation in the module README.
DEFAULT_MAX_TABLE_LENGTH = 256

# The original caps queries separately from tables, and far shorter.
DEFAULT_MAX_QUERY_LENGTH = 128

# TAPAS carries seven parallel token type ids per position.
NUM_TOKEN_TYPES = 7


def parse_markdown_table(markdown: str, max_rows: int | None = None) -> pd.DataFrame:
    """Parse a markdown table into a DataFrame of strings.

    Handles the quirks actually present in the corpus: rows with fewer or more
    cells than the header, blank header cells, and duplicate column names, any
    of which would otherwise break the tokenizer or pandas.

    Args:
        markdown: A markdown table, header row first, then a --- separator row,
            then data rows. Cells are pipe-delimited with leading and trailing
            pipes.
        max_rows: Keep at most this many data rows. The train split stores nine
            example rows and the test split two, so callers should pin this to
            keep training and indexing consistent.

    Returns:
        A DataFrame whose cells are all strings. Empty if the input has no
        parseable header.
    """
    lines = [line.strip() for line in (markdown or "").split("\n") if line.strip()]
    if not lines:
        return pd.DataFrame()

    def split_row(line: str) -> list[str]:
        # Strip the leading and trailing pipe before splitting so that they do
        # not produce phantom empty cells.
        if line.startswith("|"):
            line = line[1:]
        if line.endswith("|"):
            line = line[:-1]
        return [cell.strip() for cell in line.split("|")]

    header = split_row(lines[0])

    # Drop the |---|---| separator when present.
    body = lines[1:]
    if body and all(set(cell) <= {"-", ":"} and cell for cell in split_row(body[0])):
        body = body[1:]
    if max_rows is not None:
        body = body[:max_rows]

    # The tokenizer indexes columns by name, so names must be unique and
    # non-empty.
    columns, seen = [], {}
    for i, name in enumerate(header):
        name = name or f"col_{i}"
        if name in seen:
            seen[name] += 1
            name = f"{name}_{seen[name]}"
        else:
            seen[name] = 0
        columns.append(name)

    width = len(columns)
    rows = []
    for line in body:
        cells = split_row(line)
        # Pad short rows and clip long ones so the frame stays rectangular.
        rows.append((cells + [""] * width)[:width])

    return pd.DataFrame(rows, columns=columns, dtype=str)


def encode_tables(tokenizer, titles, tables, max_length=DEFAULT_MAX_TABLE_LENGTH):
    """Encode (title, table) pairs for the table tower.

    Args:
        tokenizer: A TapasTokenizer.
        titles: One title string per table, placed in the text slot.
        tables: One DataFrame per title.
        max_length: Sequence length cap.

    Returns:
        A dict of batched tensors ready to splat into TapasDualEncoder.encode_tables.
    """
    encoded = [
        tokenizer(
            table=table if not table.empty else pd.DataFrame({"col_0": [""]}),
            queries=[title or ""],
            padding="max_length",
            truncation="drop_rows_to_fit",
            max_length=max_length,
            return_tensors="pt",
        )
        for title, table in zip(titles, tables)
    ]
    return {
        key: torch.cat([enc[key] for enc in encoded], dim=0)
        for key in ("input_ids", "attention_mask", "token_type_ids")
    }


def encode_queries(tokenizer, queries, max_length=DEFAULT_MAX_QUERY_LENGTH):
    """Encode plain-text queries for the query tower.

    Built by hand rather than through the tokenizer's table path, because the
    query tower is defined as text against an empty table: every token type id
    is zero. Mirrors the original, which assembles [CLS] tokens [SEP] and pads.

    Args:
        tokenizer: A TapasTokenizer, used only for its wordpiece vocabulary.
        queries: The query strings.
        max_length: Sequence length cap.

    Returns:
        A dict of batched tensors ready to splat into TapasDualEncoder.encode_queries.
    """
    input_ids, attention_mask = [], []
    for query in queries:
        tokens = tokenizer.tokenize(query or "")
        # Reserve two positions for [CLS] and [SEP].
        tokens = tokens[: max_length - 2]
        ids = tokenizer.convert_tokens_to_ids(tokens)
        ids = [tokenizer.cls_token_id] + ids + [tokenizer.sep_token_id]

        mask = [1] * len(ids)
        padding = [0] * (max_length - len(ids))
        input_ids.append(ids + [tokenizer.pad_token_id] * len(padding))
        attention_mask.append(mask + padding)

    input_ids = torch.tensor(input_ids, dtype=torch.long)
    return {
        "input_ids": input_ids,
        "attention_mask": torch.tensor(attention_mask, dtype=torch.long),
        "token_type_ids": torch.zeros(*input_ids.shape, NUM_TOKEN_TYPES, dtype=torch.long),
    }
